import { build } from 'vite';
import path from 'node:path';
import fs from 'node:fs';
import { execSync } from 'node:child_process';

function getGitBuildInfo() {
  let commit = '9699f11';
  let shortCommit = '9699f11';
  const timestamp = new Date().toISOString();
  let message = 'Update Blackboarder';

  try {
    const rawCommit = execSync('git rev-parse HEAD', { encoding: 'utf8' }).trim();
    if (rawCommit) commit = rawCommit;
    const rawShort = execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim();
    if (rawShort) shortCommit = rawShort;
    const rawMsg = execSync('git log -1 --format=%s', { encoding: 'utf8' }).trim();
    if (rawMsg) message = rawMsg;
  } catch (err) {
    console.warn('⚠️ Notice: Could not read git commit directly:', err.message);
  }

  let version = '1.0.0';
  try {
    const pkg = JSON.parse(fs.readFileSync(path.resolve('package.json'), 'utf8'));
    if (pkg.version) version = pkg.version;
  } catch {}

  return {
    version,
    commit,
    shortCommit,
    timestamp,
    message,
    repo: 'yvs1n/blackboarder',
    branch: 'main'
  };
}

async function buildExtension() {
  console.log('🚀 Starting Blackboarder build...');

  const distDir = path.resolve('dist');
  const buildInfo = getGitBuildInfo();
  console.log(`📌 Target Build: ${buildInfo.version} (${buildInfo.shortCommit}) - ${buildInfo.message}`);

  // Generate src/buildInfo.ts
  const buildInfoTs = `// Auto-generated by scripts/build.js - Do not edit manually
export interface BuildInfo {
  version: string;
  commit: string;
  shortCommit: string;
  timestamp: string;
  message: string;
  repo: string;
  branch: string;
}

export const BUILD_INFO: BuildInfo = ${JSON.stringify(buildInfo, null, 2)};
`;
  fs.writeFileSync(path.resolve('src/buildInfo.ts'), buildInfoTs, 'utf8');

  // Generate version.json in root and mobile-web
  const versionJson = JSON.stringify(buildInfo, null, 2);
  fs.writeFileSync(path.resolve('version.json'), versionJson, 'utf8');
  fs.writeFileSync(path.resolve('mobile-web/version.json'), versionJson, 'utf8');

  // Synchronize APP_BUILD_COMMIT and APP_BUILD_TIMESTAMP in mobile-web/app.js
  const mobileAppPath = path.resolve('mobile-web/app.js');
  if (fs.existsSync(mobileAppPath)) {
    let appJs = fs.readFileSync(mobileAppPath, 'utf8');
    appJs = appJs.replace(
      /const APP_BUILD_COMMIT = '[^']*';/,
      `const APP_BUILD_COMMIT = '${buildInfo.shortCommit}';`
    );
    appJs = appJs.replace(
      /const APP_BUILD_TIMESTAMP = '[^']*';/,
      `const APP_BUILD_TIMESTAMP = '${buildInfo.timestamp}';`
    );
    fs.writeFileSync(mobileAppPath, appJs, 'utf8');
  }

  const viteDefines = {
    'process.env.NODE_ENV': '"production"',
    '__BUILD_VERSION__': JSON.stringify(buildInfo.version),
    '__BUILD_COMMIT__': JSON.stringify(buildInfo.commit),
    '__BUILD_SHORT_COMMIT__': JSON.stringify(buildInfo.shortCommit),
    '__BUILD_TIMESTAMP__': JSON.stringify(buildInfo.timestamp),
    '__BUILD_MESSAGE__': JSON.stringify(buildInfo.message)
  };

  // 1. Build Popup HTML
  console.log('📦 Building Popup UI...');
  await build({
    root: path.resolve('.'),
    base: '',
    build: {
      outDir: 'dist',
      emptyOutDir: true,
      rollupOptions: {
        input: {
          popup: path.resolve('src/popup/index.html')
        }
      }
    },
    define: viteDefines
  });

  // 2. Build Content Script (IIFE for isolated content world)
  console.log('📦 Building Content Script (content.js)...');
  await build({
    root: path.resolve('.'),
    build: {
      outDir: 'dist',
      emptyOutDir: false,
      lib: {
        entry: path.resolve('src/content/scraper.ts'),
        name: 'BlackboardSidekickContent',
        formats: ['iife'],
        fileName: () => 'content.js'
      }
    },
    define: viteDefines
  });

  // 3. Build Background Service Worker (IIFE standalone bundle)
  console.log('📦 Building Background Worker (background.js)...');
  await build({
    root: path.resolve('.'),
    build: {
      outDir: 'dist',
      emptyOutDir: false,
      lib: {
        entry: path.resolve('src/background/serviceWorker.ts'),
        name: 'BlackboarderBackground',
        formats: ['iife'],
        fileName: () => 'background.js'
      }
    },
    define: viteDefines
  });

  // 4. Copy Blackboard Dark Mode Script & Styles (native isolated-world theme manager)
  console.log('📦 Staging Blackboard Dark Mode Script & Styles (blackboard-dark.js)...');
  const darkCssRaw = fs.readFileSync(path.resolve('src/content/blackboard-dark.css'), 'utf8');
  const darkJsTemplate = fs.readFileSync(path.resolve('src/content/blackboard-dark.js'), 'utf8');
  const darkJsWithEmbeddedCss = darkJsTemplate.replace(
    '`__BBS_STATIC_DARK_CSS__`',
    JSON.stringify(darkCssRaw)
  );
  fs.writeFileSync(path.resolve('dist/blackboard-dark.js'), darkJsWithEmbeddedCss, 'utf8');
  fs.copyFileSync(
    path.resolve('src/content/blackboard-dark.css'),
    path.resolve('dist/blackboard-dark.css')
  );

  // 5. Copy content.css
  console.log('🎨 Copying content.css...');
  fs.copyFileSync(
    path.resolve('src/content/content.css'),
    path.resolve('dist/content.css')
  );

  // 5. Ensure manifest.json, version.json, and icons exist in dist
  console.log('📋 Ensuring manifest.json, version.json, and icons in dist...');
  if (fs.existsSync(path.resolve('public/manifest.json'))) {
    fs.copyFileSync(
      path.resolve('public/manifest.json'),
      path.resolve('dist/manifest.json')
    );
  }
  fs.writeFileSync(path.resolve('dist/version.json'), versionJson, 'utf8');

  const iconsSrcDir = path.resolve('public/icons');
  const iconsDistDir = path.resolve('dist/icons');
  if (fs.existsSync(iconsSrcDir)) {
    fs.mkdirSync(iconsDistDir, { recursive: true });
    const icons = fs.readdirSync(iconsSrcDir);
    for (const icon of icons) {
      fs.copyFileSync(path.join(iconsSrcDir, icon), path.join(iconsDistDir, icon));
    }
  }

  console.log('✅ Extension successfully built in ./dist directory!');
}

buildExtension().catch(err => {
  console.error('❌ Build failed:', err);
  process.exit(1);
});
